    private void jTableProveedoresMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableProveedoresMouseClicked
        int filaSeleccionada = jTableProveedores.getSelectedRow();
        if (filaSeleccionada >= 0) {
            idProveedorSeleccionado = Integer.parseInt(jTableProveedores.getValueAt(filaSeleccionada, 0).toString());
            txtEmpresa.setText(jTableProveedores.getValueAt(filaSeleccionada, 1).toString());
            txtContacto.setText(jTableProveedores.getValueAt(filaSeleccionada, 2) != null ? jTableProveedores.getValueAt(filaSeleccionada, 2).toString() : "");
            txtTelefono.setText(jTableProveedores.getValueAt(filaSeleccionada, 3) != null ? jTableProveedores.getValueAt(filaSeleccionada, 3).toString() : "");
        }
    }//GEN-LAST:event_jTableProveedoresMouseClicked

    private void GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GuardarActionPerformed
        String empresa = txtEmpresa.getText().trim();
        String contacto = txtContacto.getText().trim();
        String telefono = txtTelefono.getText().trim();

        if (empresa.isEmpty() || telefono.isEmpty()) {
            JOptionPane.showMessageDialog(this, "La empresa y el teléfono son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Proveedor p = new Proveedor();
        p.setNombreEmpresa(empresa);
        p.setContacto(contacto);
        p.setTelefono(telefono);

        boolean exito;

        if (idProveedorSeleccionado == -1) {
            exito = controller.insertar(p);
            if (exito) {
                JOptionPane.showMessageDialog(this, "¡Proveedor registrado con éxito!");
            }
        } else {
            p.setIdProveedor(idProveedorSeleccionado);
            exito = controller.actualizar(p);
            if (exito) {
                JOptionPane.showMessageDialog(this, "¡Proveedor actualizado con éxito!");
            }
        }

        if (exito) {
            listarProveedores();
            limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "Ocurrió un error en la base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_GuardarActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        if (idProveedorSeleccionado == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, selecciona un proveedor de la tabla para eliminar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirmar = JOptionPane.showConfirmDialog(this, "¿Estás seguro de eliminar este proveedor?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
        if (confirmar == JOptionPane.YES_OPTION) {
            boolean exito = controller.eliminar(idProveedorSeleccionado);
            if (exito) {
                JOptionPane.showMessageDialog(this, "¡Proveedor eliminado con éxito!");
                listarProveedores();
                limpiar();
            } else {
                JOptionPane.showMessageDialog(this, "Error al eliminar el proveedor.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

