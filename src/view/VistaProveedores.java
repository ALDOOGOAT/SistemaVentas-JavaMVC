    private void listarProveedores() {
        String[] columnas = {"ID", "Empresa", "Contacto", "Teléfono"};
        DefaultTableModel modelo = new DefaultTableModel(null, columnas);

        List<Proveedor> lista = controller.listar();

        for (Proveedor p : lista) {
            Object[] fila = new Object[4];
            fila[0] = p.getIdProveedor();
            fila[1] = p.getNombreEmpresa();
            fila[2] = p.getContacto();
            fila[3] = p.getTelefono();
            modelo.addRow(fila);
        }
        jTableProveedores.setModel(modelo);
    }

